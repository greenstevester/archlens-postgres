import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { after, before, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

import { Reviewer, escapeHtml, parseSchema, type Table } from '../scripts/db-review.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Paths stay relative to the skill folder because the schema path is echoed into schema.json.
const read = (p: string): string => readFileSync(path.resolve(root, p), 'utf8');
const json = (p: string): any => JSON.parse(read(p));

// Lines that legitimately differ between runs.
const VOLATILE = [/"generated_at":/, /Generated from .* on \d{4}-\d{2}-\d{2}/];
const stable = (text: string): string =>
  text.split('\n').filter((l) => !VOLATILE.some((re) => re.test(l))).join('\n');

/** Run the tool on a fixture and compare every output file with a committed golden directory. */
function goldenRun(name: string, schema: string, narratives: string, golden: string,
  files: string[], summary: RegExp, exitCode: number): void {
  describe(name, () => {
    let out = '';
    let run: ReturnType<typeof spawnSync>;

    before(() => {
      out = mkdtempSync(path.join(tmpdir(), 'db-review-'));
      run = spawnSync(
        process.execPath,
        ['--disable-warning=ExperimentalWarning', 'scripts/db-review.ts', schema, '--narratives', narratives, '--out', out],
        { cwd: root, encoding: 'utf8' },
      );
    });
    after(() => rmSync(out, { recursive: true, force: true }));

    it(`exits ${exitCode}`, () => {
      assert.equal(run.status, exitCode, `stderr: ${run.stderr}`);
    });

    it('prints the expected summary', () => {
      assert.match(String(run.stdout), summary);
    });

    for (const file of files) {
      it(`writes ${file} identical to ${golden}`, () => {
        assert.equal(stable(read(path.join(out, file))), stable(read(path.join(golden, file))));
      });
    }
  });
}

// The sample schema: 19 tables, every flaw marked in a comment. Its golden output was produced
// by the Python original; the port reproduces it byte for byte apart from the timestamp and the
// script's own name in the FINDINGS.md header.
goldenRun('sample schema (golden: examples/out)',
  'examples/sample-schema.sql', 'examples/narratives.json', 'examples/out',
  ['schema.json', 'README.md', 'FINDINGS.md', 'index.html', 'domains/tenant.md', 'domains/auth.md',
    'domains/permission.md', 'domains/github.md', 'domains/approvals.md', 'domains/billing.md'],
  /findings: 8 error, 18 warn, 12 info/, 1);

// The edge-case fixture covers what the sample lacks: a schema-qualified table, ALTER TABLE
// ADD/DROP COLUMN, FORCE ROW LEVEL SECURITY, CHECKs of every shape, partial and expression
// indexes, composite and multi-column keys, a foreign-key cycle, a wide table, block comments,
// unparsed statements, and every finding branch the sample never fires. Its golden output was
// generated by this tool and diffed against the Python original on the same input: the only
// differences were the script's name in the FINDINGS.md header and the row-value CHECK on `org`,
// which the printer renders as "…(name, kind) IS DISTINCT FROM …" (see the fallback cases below).
goldenRun('edge-case fixture (golden: test/fixtures/edge-cases.out)',
  'test/fixtures/edge-cases.sql', 'test/fixtures/edge-cases.narratives.json', 'test/fixtures/edge-cases.out',
  ['schema.json', 'README.md', 'FINDINGS.md', 'index.html', 'domains/core.md', 'domains/work.md'],
  /findings: 9 error, 8 warn, 8 info/, 1);

describe('parseSchema', () => {
  it('builds the same table model as the committed schema.json', async () => {
    const { tables } = await parseSchema(read('examples/sample-schema.sql'), 'examples/sample-schema.sql');
    const mine = JSON.parse(JSON.stringify(Object.fromEntries(tables)));
    const committed = json('examples/out/schema.json').tables;
    for (const t of Object.values(committed) as Table[]) {
      t.domain = null;
      t.findings = [];
    }
    assert.deepEqual(mine, committed);
  });
});

describe('Reviewer', () => {
  it('produces the same findings as the committed schema.json', async () => {
    const { tables } = await parseSchema(read('examples/sample-schema.sql'), 'examples/sample-schema.sql');
    const findings = new Reviewer(tables, json('examples/narratives.json')).run();
    assert.deepEqual(JSON.parse(JSON.stringify(findings)), json('examples/out/schema.json').findings);
  });
});

